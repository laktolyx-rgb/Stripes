// Renders templates/<app>/template.js into ports/<app>/.
//
// A template is a plain ES module:
//   export const meta = { name, category, homepage, install }
//   export function render(ctx) { return { 'relative/file.ext': 'contents', ... } }
// ctx = { variants, variant(id), palette, config, h, meta }
// Files in templates/<app>/static/ are copied verbatim (handwritten code, images, docs).
// ports/<app>/ is fully generated: build wipes it, and check fails if it differs.
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { ROOT, loadPalette, resolveAll } from './palette.js';
import * as color from './color.js';
import { loadConfig, fill } from './config.js';

export const TEMPLATES = path.join(ROOT, 'templates');
export const PORTS = path.join(ROOT, 'ports');

export const h = {
  ...color,
  /** "#d15858" -> "d15858" */
  noHash: (hex) => hex.replace('#', ''),
  /** "#d15858" -> "209, 88, 88" */
  rgbList: (hex) => { const { r, g, b } = color.hexToRgb(hex); return `${r}, ${g}, ${b}`; },
  /** "#d15858" -> "0xd15858" */
  hex0x: (hex) => '0x' + hex.replace('#', ''),
  /** fontStyle string for TextMate/VS Code */
  fontStyle: (role) => [role.bold && 'bold', role.italic && 'italic'].filter(Boolean).join(' '),
  json: (obj) => JSON.stringify(obj, null, 2) + '\n',
  title: (s) => s[0].toUpperCase() + s.slice(1),
};

export function listApps() {
  if (!existsSync(TEMPLATES)) return [];
  return readdirSync(TEMPLATES).filter((d) => existsSync(path.join(TEMPLATES, d, 'template.js'))).sort();
}

function walk(dir, base = dir) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir).flatMap((f) => {
    const p = path.join(dir, f);
    return statSync(p).isDirectory() ? walk(p, base) : [path.relative(base, p).split(path.sep).join('/')];
  });
}

const TEXT = /\.(md|txt|lua|kts|toml|json|css|xml|yml|yaml)$/i;

export async function renderApp(app, palette = loadPalette(), config = loadConfig()) {
  const dir = path.join(TEMPLATES, app);
  const mod = await import(pathToFileURL(path.join(dir, 'template.js')).href);
  const variants = resolveAll(palette);
  const ctx = { variants, variant: (id) => variants.find((v) => v.id === id), palette, config, h, meta: mod.meta };
  const files = new Map();
  for (const rel of walk(path.join(dir, 'static'))) {
    const buf = readFileSync(path.join(dir, 'static', rel));
    // static text files may use {{repoUrl}}, {{rawUrl}}, {{vscodeId}}, ... from stripes.config.json
    files.set(rel, TEXT.test(rel) ? Buffer.from(fill(buf.toString('utf8'), config)) : buf);
  }
  for (const [rel, content] of Object.entries(await mod.render(ctx))) {
    const text = String(content);
    files.set(rel, Buffer.from(text.endsWith('\n') ? text : text + '\n'));
  }
  return { app, meta: mod.meta, files };
}

export async function build(apps = listApps()) {
  const palette = loadPalette();
  const index = [];
  for (const app of apps) {
    const { meta, files } = await renderApp(app, palette);
    const out = path.join(PORTS, app);
    rmSync(out, { recursive: true, force: true });
    for (const [rel, buf] of files) {
      mkdirSync(path.dirname(path.join(out, rel)), { recursive: true });
      writeFileSync(path.join(out, rel), buf);
    }
    index.push({ id: app, ...meta, files: [...files.keys()].sort() });
    console.log(`  ✓ ${app.padEnd(18)} ${files.size} files`);
  }
  if (apps.length === listApps().length) {
    writeFileSync(path.join(PORTS, 'index.json'), h.json({ version: palette.version, ports: index }));
    writeFileSync(path.join(PORTS, 'README.md'), portsReadme(index));
  }
  return index;
}

/** Returns a list of out-of-date files; empty means ports/ matches the templates. */
export async function check(apps = listApps()) {
  const palette = loadPalette();
  const problems = [];
  for (const app of apps) {
    const { files } = await renderApp(app, palette);
    const out = path.join(PORTS, app);
    const onDisk = new Set(walk(out));
    for (const [rel, buf] of files) {
      const p = path.join(out, rel);
      if (!existsSync(p)) problems.push(`missing  ports/${app}/${rel}`);
      else if (!readFileSync(p).equals(buf)) problems.push(`changed  ports/${app}/${rel}`);
      onDisk.delete(rel);
    }
    for (const rel of onDisk) problems.push(`extra    ports/${app}/${rel}`);
  }
  return problems;
}

function portsReadme(index) {
  const rows = index.map((p) => `| [${p.name}](./${p.id}) | ${p.category} | ${p.install ?? ''} |`).join('\n');
  return `<!-- Generated by \`npm run build\`. Do not edit. -->
# Stripes ports

| App | Category | Install |
|---|---|---|
${rows}
`;
}

export function scaffold(app) {
  const dir = path.join(TEMPLATES, app);
  if (existsSync(dir)) throw new Error(`templates/${app} already exists`);
  mkdirSync(path.join(dir, 'static'), { recursive: true });
  writeFileSync(path.join(dir, 'template.js'), `// Stripes port for ${app}. Read CONTRIBUTING.md and palette/spec.md.
export const meta = {
  name: '${h.title(app)}',
  category: 'other',            // editor | terminal | app | ...
  homepage: 'https://example.com',
  install: 'Copy the file for your variant into ...',
};

// Return { 'path/inside/ports/${app}': 'file contents' }.
// Use roles (r.keyword.hex), not color names, so the spec stays consistent.
export function render({ variants, h }) {
  const files = {};
  for (const v of variants) {
    const r = v.roles;
    files[\`stripes-\${v.id}.conf\`] = \`# \${v.name}
background \${r.background.hex}
foreground \${r.foreground.hex}
accent     \${r.accent.hex}
\`;
  }
  return files;
}
`);
  writeFileSync(path.join(dir, 'static', 'README.md'), `# Stripes for ${h.title(app)}\n\n## Install\n\nTODO\n`);
  return dir;
}
