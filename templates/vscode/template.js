function semanticTokenColors(v, h) {
  const r = v.roles;
  const s = (role, extra = {}) => ({ foreground: role.hex, ...(role.bold ? { bold: true } : {}), ...(role.italic ? { italic: true } : {}), ...extra });
  return {
    namespace: s(r.type),
    type: s(r.type), class: s(r.type), interface: s(r.type), struct: s(r.type), enum: s(r.type), typeParameter: s(r.type),
    'class.defaultLibrary': s(r.type), 'type.defaultLibrary': s(r.type),
    function: s(r.function), method: s(r.method), 'function.defaultLibrary': s(r.function), macro: s(r.function, { bold: true }),
    decorator: s(r.attribute),
    variable: s(r.variable), 'variable.readonly': s(r.constant), 'variable.defaultLibrary': s(r.constant), 'variable.constant': s(r.constant),
    parameter: s(r.parameter),
    property: s(r.property), 'property.readonly': s(r.property), enumMember: s(r.constant),
    keyword: s(r.keyword), selfKeyword: s(r.storage), builtinConstant: s(r.constant),
    string: s(r.string), number: s(r.number), regexp: s(r.regex), operator: s(r.operator),
    comment: s(r.comment), lifetime: s(r.regex, { italic: true }),
    '*.deprecated': { strikethrough: true },
  };
}

function theme(v, h) {
  return {
    $schema: 'vscode://schemas/color-theme',
    name: v.name,
    type: v.dark ? 'dark' : 'light',
    semanticHighlighting: true,
    colors: workbench(v, h),
    tokenColors: tokenColors(v, h),
    semanticTokenColors: semanticTokenColors(v, h),
  };
}

export function render({ variants, h, palette }) {
  const files = {};
  for (const v of variants) files[`themes/stripes-${v.id}-color-theme.json`] = h.json(theme(v, h));
  files['package.json'] = h.json({
    name: 'stripes',
    displayName: 'Stripes Theme',
    description: 'A gothic black & white theme with a single drop of blood. Night, Bone, Void and Blood (high contrast).',
    version: EXT_VERSION,
    publisher: 'stripes-theme',
    license: 'MIT',
    icon: 'icon.png',
    galleryBanner: { color: '#101010', theme: 'dark' },
    engines: { vscode: '^1.70.0' },
    categories: ['Themes'],
    keywords: ['theme', 'dark', 'light', 'gothic', 'monochrome', 'black and white', 'high contrast', 'oled', 'minimal', 'red'],
    repository: { type: 'git', url: 'https://github.com/stripes-theme/stripes', directory: 'ports/vscode' },
    bugs: { url: 'https://github.com/stripes-theme/stripes/issues' },
    homepage: 'https://github.com/stripes-theme/stripes#readme',
    contributes: {
      themes: variants.map((v) => ({
        label: v.name,
        uiTheme: v.dark ? 'vs-dark' : 'vs',
        path: `./themes/stripes-${v.id}-color-theme.json`,
      })),
    },
  });
  return files;
}
