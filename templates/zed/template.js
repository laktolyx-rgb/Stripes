// Zed extension: one theme family file with all 4 variants.
export const meta = {
  name: 'Zed',
  category: 'editor',
  homepage: 'https://zed.dev',
  install: 'Zed → Extensions → search "Stripes"',
};

function style(v, h) {
  const r = v.roles, c = Object.fromEntries(Object.entries(v.colors).map(([k, x]) => [k, x.hex]));
  const a = h.withAlpha;
  const syn = (role, extra = {}) => ({
    color: role.hex,
    font_style: role.italic ? 'italic' : null,
    font_weight: role.bold ? 700 : null,
    ...extra,
  });
  const ansi = {};
  for (const n of ['black', 'red', 'green', 'yellow', 'blue', 'magenta', 'cyan', 'white']) {
    ansi[`terminal.ansi.${n}`] = v.ansi.normal[n];
    ansi[`terminal.ansi.bright_${n}`] = v.ansi.bright[n];
    ansi[`terminal.ansi.dim_${n}`] = h.mix(v.ansi.normal[n], r.background.hex, 0.35);
  }
  return {
    'background.appearance': 'opaque',
    background: c.crypt,
    border: c.grave,
    'border.variant': c.grave,
    'border.focused': c.blood,
    'border.selected': c.blood,
    'border.transparent': '#00000000',
    'border.disabled': c.grave,
    'elevated_surface.background': c.crypt,
    'surface.background': c.crypt,
    'element.background': c.grave,
    'element.hover': c.tomb,
    'element.active': c.tomb,
    'element.selected': c.tomb,
    'element.disabled': c.grave,
    'drop_target.background': a(c.blood, 0.2),
    'ghost_element.background': '#00000000',
    'ghost_element.hover': a(c.tomb, 0.7),
    'ghost_element.active': c.tomb,
    'ghost_element.selected': c.tomb,
    'ghost_element.disabled': '#00000000',
    text: c.bone,
    'text.muted': c.fog,
    'text.placeholder': c.fog,
    'text.disabled': c.ash,
    'text.accent': c.blood,
    icon: c.smoke,
    'icon.muted': c.fog,
    'icon.disabled': c.ash,
    'icon.placeholder': c.fog,
    'icon.accent': c.blood,
    'status_bar.background': c.crypt,
    'title_bar.background': c.crypt,
    'title_bar.inactive_background': c.crypt,
    'toolbar.background': c.midnight,
    'tab_bar.background': c.crypt,
    'tab.inactive_background': c.crypt,
    'tab.active_background': c.midnight,
    'search.match_background': a(c.blood, 0.35),
    'panel.background': c.crypt,
    'panel.focused_border': c.blood,
    'pane.focused_border': c.blood,
    'scrollbar.thumb.background': a(c.ash, 0.4),
    'scrollbar.thumb.hover_background': a(c.ash, 0.7),
    'scrollbar.thumb.border': '#00000000',
    'scrollbar.track.background': '#00000000',
    'scrollbar.track.border': '#00000000',
    'editor.foreground': c.bone,
    'editor.background': c.midnight,
    'editor.gutter.background': c.midnight,
    'editor.subheader.background': c.crypt,
    'editor.active_line.background': a(c.grave, 0.8),
    'editor.highlighted_line.background': c.grave,
    'editor.line_number': c.ash,
    'editor.active_line_number': c.ivory,
    'editor.invisible': c.grave,
    'editor.wrap_guide': c.grave,
    'editor.active_wrap_guide': c.ash,
    'editor.indent_guide': c.grave,
    'editor.indent_guide_active': c.ash,
    'editor.document_highlight.read_background': a(c.smoke, 0.12),
    'editor.document_highlight.write_background': a(c.smoke, 0.2),
    'editor.document_highlight.bracket_background': a(c.blood, 0.2),
    'terminal.background': c.crypt,
    'terminal.foreground': c.bone,
    'terminal.bright_foreground': c.ivory,
    'terminal.dim_foreground': c.fog,
    ...ansi,
    'link_text.hover': c.blood,
    error: r.error.hex, 'error.background': c.scar, 'error.border': r.error.hex,
    warning: r.warning.hex, 'warning.background': c.grave, 'warning.border': r.warning.hex,
    info: r.info.hex, 'info.background': c.grave, 'info.border': r.info.hex,
    hint: r.hint.hex, 'hint.background': c.grave, 'hint.border': c.ash,
    success: c.bone, 'success.background': c.grave, 'success.border': c.bone,
    created: c.bone, 'created.background': a(c.bone, 0.08), 'created.border': c.bone,
    modified: c.smoke, 'modified.background': a(c.smoke, 0.08), 'modified.border': c.smoke,
    deleted: r.error.hex, 'deleted.background': c.scar, 'deleted.border': r.error.hex,
    conflict: c.blood, 'conflict.background': c.scar, 'conflict.border': c.blood,
    ignored: c.ash, 'ignored.background': c.crypt, 'ignored.border': c.grave,
    hidden: c.ash, 'hidden.background': c.crypt, 'hidden.border': c.grave,
    renamed: c.smoke, 'renamed.background': c.grave, 'renamed.border': c.smoke,
    unreachable: c.fog, 'unreachable.background': c.crypt, 'unreachable.border': c.grave,
    predictive: c.ash, 'predictive.background': c.crypt, 'predictive.border': c.grave,
    players: [
      { cursor: c.ivory, background: c.ivory, selection: a(c.tomb, 1) },
      { cursor: c.blood, background: c.blood, selection: a(c.blood, 0.25) },
      { cursor: c.smoke, background: c.smoke, selection: a(c.smoke, 0.25) },
      { cursor: c.ember, background: c.ember, selection: a(c.ember, 0.25) },
    ],
    syntax: {
      attribute: syn(r.attribute),
      boolean: syn(r.constant),
      comment: syn(r.comment),
      'comment.doc': syn(r.comment),
      constant: syn(r.constant),
      constructor: syn(r.type),
      embedded: syn(r.foreground),
      emphasis: { color: c.bone, font_style: 'italic' },
      'emphasis.strong': { color: c.ivory, font_weight: 700 },
      enum: syn(r.type),
      function: syn(r.function),
      'function.method': syn(r.method),
      hint: syn(r.hint),
      keyword: syn(r.keyword),
      label: syn(r.punctuation),
      link_text: syn(r.accent),
      link_uri: syn(r.accent, { font_style: 'italic' }),
      namespace: syn(r.type),
      number: syn(r.number),
      operator: syn(r.operator),
      predictive: { color: c.ash, font_style: 'italic' },
      preproc: syn(r.keyword),
      primary: syn(r.foreground),
      property: syn(r.property),
      punctuation: syn(r.punctuation),
      'punctuation.bracket': syn(r.punctuation),
      'punctuation.delimiter': syn(r.punctuation),
      'punctuation.list_marker': syn(r.accent),
      'punctuation.special': syn(r.regex),
      selector: syn(r.keyword),
      'selector.pseudo': syn(r.attribute),
      string: syn(r.string),
      'string.escape': syn(r.escape),
      'string.regex': syn(r.regex),
      'string.special': syn(r.regex),
      'string.special.symbol': syn(r.constant),
      tag: syn(r.tag),
      'text.literal': syn(r.string),
      title: syn(r.keyword),
      type: syn(r.type),
      'type.builtin': syn(r.type),
      variable: syn(r.variable),
      'variable.special': syn(r.storage),
      'variable.parameter': syn(r.parameter),
      variant: syn(r.constant),
    },
  };
}

export function render({ variants, h, palette }) {
  return {
    'themes/stripes.json': h.json({
      $schema: 'https://zed.dev/schema/themes/v0.2.0.json',
      name: 'Stripes',
      author: 'Stripes contributors',
      themes: variants.map((v) => ({ name: v.name, appearance: v.dark ? 'dark' : 'light', style: style(v, h) })),
    }),
    'extension.toml': `id = "stripes"
name = "Stripes"
version = "${palette.version}"
schema_version = 1
authors = ["Stripes contributors"]
description = "A gothic black & white theme with a single drop of blood."
repository = "https://github.com/stripes-theme/stripes"
`,
  };
}
